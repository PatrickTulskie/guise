package main

import "strings"

// What `setup` writes out and `update` rewrites: shims that call back into
// this binary, the shell hook, and the git config template.

// Wrap a path so a shell sees one word whatever is in it.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func installedGuise() string { return gitPath(binDir + "/" + exeName) }

func shim(comment string, args ...string) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# " + comment + "\n")
	b.WriteString("# Written by `guise setup`, rewritten by `guise update`; edits here are lost.\n")
	b.WriteString("exec " + shellQuote(installedGuise()))
	for _, a := range args {
		b.WriteString(" " + a)
	}
	b.WriteString(" \"$@\"\n")
	return b.String()
}

func helperShim(name string) string {
	switch name {
	case "guise-token":
		return shim("guise-token: print a GitHub credential for an identity -- a minted installation token for an app, the stored PAT for an account.", "token")
	case "guise-credential":
		return shim("guise-credential: the git credential helper the rendered conf names, answering `get` with the identity's token.", "_credential")
	default:
		return shim("guise-gh: run gh as the identity owning the current directory, with GH_TOKEN set to its token.", "_gh")
	}
}

// Credit the human as co-author on every commit the agent authors, in place
// of the one a harness stamps for itself.
func hookShim() string {
	return shim("guise's prepare-commit-msg hook: adds the human's Co-authored-by trailer to the agent's commits.", "_hook", "prepare-commit-msg")
}

// Git runs exactly one hooks directory per repository, and inside an
// identity's directory the rendered conf makes that guise's. One copy of this
// per hook name runs the repository's own hook of that name, then guise's.
func dispatcherShim() string {
	return shim("Run the repository's own hook of this name, then guise's.", "_dispatch", `"$0"`)
}

// Sourced into an interactive zsh/bash by a marked line in the shell rc. Only
// `use` needs it: changing the caller's directory is something no child
// process can do, so `use --emit-shell` prints the cd and this runs it.
const shellHook = `# guise shell integration -- written by ` + "`guise setup`" + `, do not edit.
# Rewritten by ` + "`guise update`" + `; edits here are lost.

guise() {
  if [ "${1:-}" = use ]; then
    shift
    local __guise_cd
    __guise_cd=$(command guise use --emit-shell "$@") || return $?
    eval "$__guise_cd"
  else
    command guise "$@"
  fi
}
`

const agentConfTemplate = `# Generated by guise -- do not hand-edit; re-run ` + "`guise setup`" + ` instead.

[user]
	name = {{GIT_NAME}}
	email = {{GIT_EMAIL}}{{SIGNINGKEY}}

{{SIGNING}}

[credential "https://github.com"]
	# Empty value CLEARS inherited helpers (osxkeychain), otherwise the
	# human's cached credentials win and commits push as the human.
	helper =
	helper = {{BIN_DIR}}/guise-credential {{NAME}}

[core]
	# A dispatcher: the repository's own hooks run first, then guise's.
	hooksPath = {{DISPATCH_DIR}}

[guise]
	# What the dispatcher reads to tell agent scope from a clone that left it.
	identity = {{NAME}}

[url "https://github.com/"]
	# ssh would authenticate as the human's key; force https so the
	# credential helper (and therefore the bot identity) always wins.
	insteadOf = git@github.com:
`

// Stated rather than inherited: the identity has no signing key, and the
// human's global config almost certainly sets gpgsign true.
const signingOffBlock = `[commit]
	gpgsign = false

[tag]
	gpgsign = false`

func signingOnBlock(allowedSignersPath string) string {
	return `[commit]
	gpgsign = true

[tag]
	gpgsign = true

[gpg]
	format = ssh

[gpg "ssh"]
	# Lets 'git log --show-signature' verify locally. GitHub verifies against
	# its own copy of the public key, registered on the agent account.
	allowedSignersFile = ` + allowedSignersPath + `
	# Stated rather than inherited: a global signer such as 1Password's
	# op-ssh-sign cannot use a key file on disk, and fails every commit here.
	program = ssh-keygen`
}

